/** Đèn lồng: nắp hẹp ở trên, thân rộng ở dưới. */
export const lampPoly = ([x1, y1, x2, y2]: [number, number, number, number]): P => {
  const w = x2 - x1, h = y2 - y1, cx = (x1 + x2) / 2
  return [[cx - w * 0.2, y1], [cx + w * 0.2, y1], [x2 - w * 0.08, y1 + h * 0.2], [x2, y1 + h * 0.3], [x2, y2 - h * 0.08], [x2 - w * 0.12, y2], [x1 + w * 0.12, y2], [x1, y2 - h * 0.08], [x1, y1 + h * 0.3], [x1 + w * 0.08, y1 + h * 0.2]].map(([x, y]) => [Math.round(x), Math.round(y)] as [number, number])
}
export const polyBox = (p: P) => {
  const xs = p.map((q) => q[0]), ys = p.map((q) => q[1])
  return { x: Math.min(...xs), y: Math.min(...ys), w: Math.max(...xs) - Math.min(...xs), h: Math.max(...ys) - Math.min(...ys) }
}
